function parsePortions(spec: string): Portion[] {
  return spec
    .split(',')
    .map((item) => item.trim())
    .filter(Boolean)
    .map((item) => {
      const [name, grams] = item.split(':')
      return { name, grams: Number(grams) }
    })
}

